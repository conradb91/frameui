const { _electron } = require('playwright-core')
const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), assert = require('node:assert/strict'), crypto = require('node:crypto')
;(async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'frameui-vector-check-'))
  const source = path.join(root, 'Vector fixture')
  fs.cpSync(path.resolve('tests/fixtures/editor-project'), source, { recursive: true })
  const sourceHash = () => crypto.createHash('sha256').update(fs.readdirSync(source).sort().map(file => file + fs.readFileSync(path.join(source, file), 'utf8')).join('\n')).digest('hex')
  const originalHash = sourceHash()
  const env = { ...process.env, FRAMEUI_ALLOW_MULTIPLE_INSTANCES: '1' }; delete env.ELECTRON_RUN_AS_NODE
  let app, profile, metadata
  try {
    app = await _electron.launch({ executablePath: process.env.FRAMEUI_PACKAGED_APP || path.resolve('release/repo-design-review/mac/FrameUI.app/Contents/MacOS/FrameUI'), env })
    await app.evaluate(({ app }) => {
      global.__repoViolations = []
      const require = process.mainModule.require.bind(process.mainModule)
      require('node:net').Server.prototype.listen = function () { global.__repoViolations.push('listen'); throw new Error('Repo design must not open a server') }
      for (const method of ['spawn','exec','execFile','fork']) require('node:child_process')[method] = function () { global.__repoViolations.push(method); throw new Error('Repo design must not execute project commands') }
      app.on('web-contents-created', (_event, contents) => contents.on('did-start-navigation', (_event, url) => { if (/^https?:/.test(url)) global.__repoViolations.push(url) }))
    })
    const page = await app.firstWindow()
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    const info = await app.evaluate(({ app }) => ({ profile: app.getPath('userData'), appPath: app.getAppPath(), packaged: app.isPackaged }))
    metadata = JSON.parse(require('@electron/asar').extractFile(info.appPath, 'package.json').toString()).frameuiReviewProfile
    profile = info.profile
    assert(info.packaged); assert.equal(path.basename(profile), metadata)
    await page.getByRole('button', { name: 'Open Codebase', exact: true }).waitFor()
    assert.deepEqual(await page.evaluate(() => window.frameui.design.list()), [])
    await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }) }, source)
    await page.getByRole('button', { name: 'Open Codebase', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Project analysis' })
    await dialog.waitFor({ timeout: 60000 })
    await dialog.getByRole('button', { name: 'Open workspace', exact: true }).click()
    assert.equal(await page.getByRole('button', {name:'Start local application',exact:true}).count(), 0)
    const before = await page.evaluate(async () => {const [file] = await window.frameui.design.list(); return window.frameui.design.load(file.id)})
    assert.equal(before.pages.length, 0)
    assert(before.pageRegistry.length >= 2)
    await page.getByRole('button', { name: /^Open .*Design from your code/i }).click()
    await page.getByRole('button', { name: 'Rectangle (R)', exact: true }).waitFor({timeout:60000})
    console.log('Source-only import and progressive page creation passed; checking vector editing.')
    const library = await page.evaluate(async () => {
      const files = await window.frameui.design.list()
      return window.frameui.design.load(files.find(file => file.projectId && !file.libraryId).id)
    })
    assert.equal(library.pages.length, 1)
    const flattened = []; const walk = objects => objects.forEach(o => { flattened.push(o); walk(o.children) }); walk(library.pages[0].objects)
    assert(flattened.some(o => o.kind === 'Text' && o.text.includes('Design from your code')))
    assert(flattened.some(o => o.fill === 'rgb(37, 99, 235)' || o.fill === '#2563eb'))
    assert(library.pageRegistry.length >= 2)
    await page.getByRole('button', { name: 'Rectangle (R)', exact: true }).waitFor()
    for (const tool of ['Frame (F)', 'Ellipse (O)', 'Line (L)', 'Pen (P)', 'Text (T)', 'Hand (H)']) assert(await page.getByRole('button', { name: tool, exact: true }).isVisible())
    const stage = page.locator('.ide-stage')
    await stage.locator('tspan').filter({hasText: /^Design from your code$/}).dblclick()
    await page.locator('.ide-inline-text').fill('Edited imported heading')
    await page.locator('.ide-inline-text').press('Tab')
    const box = await stage.boundingBox()
    await page.getByRole('button', { name: 'Rectangle (R)', exact: true }).click()
    await page.mouse.move(box.x + box.width * .55, box.y + box.height * .60)
    await page.mouse.down(); await page.mouse.move(box.x + box.width * .75, box.y + box.height * .75, { steps: 10 }); await page.mouse.up()
    await page.getByRole('button', { name: 'Text (T)', exact: true }).click()
    await page.mouse.click(box.x + box.width * .5, box.y + box.height * .45)
    await page.locator('.ide-inspector textarea').fill('Designer edited text')
    await page.locator('.ide-inspector textarea').press('Tab')
    await page.waitForFunction(async () => {
      const files = await window.frameui.design.list(); const file = files.find(f => f.libraryId)
      if (!file) return false
      const document = await window.frameui.design.load(file.id)
      return JSON.stringify(document).includes('Designer edited text')
    })
    const saved = await page.evaluate(async () => { const files = await window.frameui.design.list(); return window.frameui.design.load(files.find(f => f.libraryId).id) })
    assert(saved.pages[0].objects.some(o => o.kind === 'Rectangle'))
    assert(saved.pages[0].objects.some(o => o.kind === 'Text' && o.width >= 200 && o.height >= 16))
    console.log('Import, rendering, drawing and saved edits passed; checking native SVG export.')
    const exportPath = path.join(root, 'design.svg')
    await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }) }, exportPath)
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.send('design:command', 'export'))
    await page.getByRole('dialog', { name: 'Export design' }).getByRole('button', { name: 'Export SVG', exact: true }).click()
    await page.getByText('Editable SVG saved', { exact: true }).waitFor()
    const svg = fs.readFileSync(exportPath, 'utf8')
    assert(svg.includes('<svg')); assert(svg.includes('<text')); assert(svg.includes('Designer edited text')); assert(!svg.includes('<foreignObject'))
    assert(svg.includes('Edited imported heading'))
    assert.equal(sourceHash(), originalHash)
    assert.deepEqual(await app.evaluate(() => global.__repoViolations), [])
    assert.deepEqual(errors, [])
    await page.screenshot({ path: '/tmp/frameui-vector-editor-review.png' })
    const reactSource = path.join(root, 'React fixture')
    fs.cpSync(path.resolve('tests/fixtures/source-react'), reactSource, {recursive:true})
    const sourceResult = await page.evaluate(async folder => {
      await window.frameui.project.openPath(folder)
      const index = await window.frameui.project.getIndex()
      const target = index.projectModel.pages.find(p => p.source.filePath.endsWith('Users.tsx'))
      if (!target) throw new Error('Users source route missing from index')
      const input = {projectId:index.projectId,pageId:target.id}
      const populated=await window.frameui.design.fromSource({...input,width:1440})
      const loading=await window.frameui.design.fromSource({...input,state:'Loading'})
      const empty=await window.frameui.design.fromSource({...input,state:'Empty'})
      const mobile=await window.frameui.design.fromSource({...input,width:375})
      const cached=await window.frameui.design.fromSource({...input,width:375})
      return {populated,loading,empty,mobile,cached}
    },reactSource)
    const textOf = value => JSON.stringify(value.objects)
    assert(textOf(sourceResult.populated).includes('Sarah Mitchell'))
    assert(textOf(sourceResult.populated).includes('nicole.adams@example.com'))
    assert(textOf(sourceResult.loading).includes('Loading users'))
    assert(!textOf(sourceResult.loading).includes('Sarah Mitchell'))
    assert(textOf(sourceResult.empty).includes('No users yet'))
    assert.equal(sourceResult.mobile.width,375)
    const cards = objects => {
      const found=[]
      const walk=(nodes,x=0,y=0)=>nodes.forEach(node=>{if(node.name==='User Card')found.push({x:x+node.x,y:y+node.y,width:node.width});walk(node.children,x+node.x,y+node.y)})
      walk(objects);return found
    }
    const desktopCards=cards(sourceResult.populated.objects), mobileCards=cards(sourceResult.mobile.objects)
    assert.equal(desktopCards.length,5);assert.equal(mobileCards.length,5)
    assert(desktopCards[1].x>desktopCards[0].x)
    assert.equal(mobileCards[1].x,mobileCards[0].x)
    assert(mobileCards[1].y>mobileCards[0].y)
    assert.equal(sourceResult.cached.id,sourceResult.mobile.id)
    assert(sourceResult.populated.sourceDesign.generatedData)
    assert.deepEqual(await app.evaluate(() => global.__repoViolations), [])
    console.log('PASS: React source components, generated populated data, loading/empty states, responsive source resolution and cache reuse without starting the application.')
    console.log('PASS: no-server repository import, progressive source reconstruction, imported text editing, shapes, persistence, editable SVG export, and unchanged source files.')
  } finally {
    if (app) await app.close()
    if (profile && metadata) { assert(path.basename(profile) === metadata && metadata.startsWith('review-')); fs.rmSync(profile, { recursive: true, force: true }) }
    fs.rmSync(root, { recursive: true, force: true })
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
