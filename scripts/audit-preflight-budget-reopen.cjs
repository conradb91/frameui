const { app, dialog, net } = require('electron')
const fs = require('node:fs/promises'), path = require('node:path'), assert = require('node:assert/strict')
const engine = require('../hosting/stacker/engine.cjs')
const { scanDatabaseSources } = require('../hosting/stacker/lib/database-sources.cjs')
;(async () => {
 const profile = process.env.FRAMEUI_BUDGET_PROFILE || '/var/folders/90/gc1n68853tjdwz7gdsdnbvlm0000gn/T/frameui-preflight-budget-M4Utoo'
 app.setPath('userData', profile); await app.whenReady()
 const state = JSON.parse(await fs.readFile(path.join(profile, 'LocalEnvironment/state.json'), 'utf8'))
 const saved = state.projects.find(project => project.database?.managed)
 assert(saved, 'a verified Budget audit profile is required')
 await engine.initialize(null, (channel, event) => { if (channel === 'setup:progress') console.log(event.stage, event.status || '') })
 try {
  const found = await engine.inspect(saved.path)
  const options = { installDependencies: true, createEnvironment: true, environmentMode: 'local', database: 'mariadb', databaseMode: 'create', databaseEngine: 'mariadb', databaseSource: saved.preparedDatabaseSource, preflightDatabase: true, startWhenReady: true, runtimeVersion: found.plan.steps.find(s => s.id === 'runtime')?.version }
  await engine.invoke('projects:setup', saved.id, options)
  const reopened = engine.snapshot(saved.id)
  assert.equal(reopened.setup.steps.running_migrations.finishedAt, saved.setup.steps.running_migrations.finishedAt)
  assert(reopened.process.running)
  assert((await net.fetch(reopened.localUrl)).status < 500)
  await engine.invoke('processes:stop', saved.id)
  console.log('PASS Budget restart uses the existing database without rerunning migrations')
  const clone = path.join(profile, 'sql-audit', 'Budget-sql')
  await fs.mkdir(path.dirname(clone), { recursive: true })
  await fs.cp(saved.path, clone, { recursive: true, filter: file => !path.basename(file).startsWith('.frameui-') && path.basename(file) !== '.git' })
  const dump = path.join(clone, 'database.sql')
  dialog.showSaveDialog = async () => ({ canceled: false, filePath: dump })
  await engine.invoke('database-services:dump', saved.id)
  const imported = await engine.inspect(clone)
  const source = (await scanDatabaseSources(clone)).find(source => source.path === 'database.sql')
  assert(source)
  await engine.invoke('projects:setup', imported.project.id, { ...options, runtimeVersion: imported.plan.steps.find(s => s.id === 'runtime')?.version, databaseSource: source })
  const result = engine.snapshot(imported.project.id)
  assert.equal(result.setup.steps.importing_database.status, 'completed')
  assert(result.process.running)
  assert((await net.fetch(result.localUrl)).status < 500)
  console.log('PASS real Budget with MariaDB/MySQL SQL dump, tables verified before startup')
 } finally { await engine.shutdown(); app.quit() }
})().catch(error => { console.error(error); app.exit(1) })
