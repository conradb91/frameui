const { _electron: electron } = require('playwright-core');
const fs = require('fs');
const os = require('os');
const path = require('path');
let application;
(async () => {
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'frameui-smoke-'));
 fs.writeFileSync(path.join(root,'index.php'), '<!doctype html><html><head><link rel="stylesheet" href="app.css"></head><body><main class="container"><nav>Northstar · Your account</nav><h1>Your next adventure starts here.</h1><p>A real project page, with its own typography and colour.</p><button class="primary">Plan a journey</button></main></body></html>');
 fs.writeFileSync(path.join(root,'payment.php'), '<main class="container"><h1>Payment</h1><form><label>Cardholder name<input placeholder="Name on card"></label><button class="primary">Pay securely</button></form></main>');
 fs.writeFileSync(path.join(root,'app.css'), 'body{font-family:Helvetica,sans-serif;background:#f1f4ee;color:#163b2a}.container{max-width:1100px;margin:0 auto;padding:48px}nav{padding:20px 0;border-bottom:1px solid #bbcebf}h1{font-size:48px;margin-top:90px;max-width:650px}p{font-size:18px}button.primary{padding:16px 28px;background:#21644c;border:0;border-radius:6px;color:white;font-size:16px}input{display:block;padding:16px;margin:20px 0;border:1px solid #80998a}@media(min-width:760px){.container{padding:40px}}@media(min-width:1180px){.container{padding:60px}}');
 const app=application=await electron.launch({executablePath:require('electron'),args:[path.resolve(__dirname, '..'),`--user-data-dir=${root}-profile`],env:{...process.env,FRAMEUI_ALLOW_MULTIPLE_INSTANCES:'1',ELECTRON_RUN_AS_NODE:''}});
 const page=await app.firstWindow();
 page.on('pageerror',e=>console.log('PAGE ERROR',e.message));
 await page.waitForLoadState('domcontentloaded');
 await app.evaluate(({dialog}, root) => { dialog.showOpenDialog = async () => ({canceled:false,filePaths:[root]}); }, root);
 await page.getByRole('radio', {name:'Light',exact:true}).check();
 await page.screenshot({path:path.join(os.tmpdir(), 'frameui-welcome.png')});
 await page.getByRole('button',{name:'Get started'}).click();
 await page.getByRole('button',{name:'Application settings',exact:true}).click();
 await page.getByRole('radio',{name:'Dark',exact:true}).check();
 await page.getByRole('button',{name:'Close settings',exact:true}).click();
 await page.getByRole('button',{name:'Open Project',exact:true}).first().click();
 await page.getByRole('heading',{name:'A place for your next idea.'}).waitFor({timeout:20000});
 await page.screenshot({path:path.join(os.tmpdir(), 'frameui-home.png')});
 await page.getByRole('button',{name:/Feature Flow/}).click();
 await page.getByRole('textbox',{name:'Design name'}).fill('Purchase flow');
 await page.getByText('Index',{exact:true}).click();
 await page.getByText('Payment',{exact:true}).click();
 await page.getByRole('button',{name:'Open 2 screens'}).click();
 await page.getByTitle('Focus canvas').waitFor();
 const runtime = await page.evaluate(async () => { for(let i=0;i<80;i++){ const status=await window.frameui.preview.getStatus(); if(status.status==='running' && status.url) return status; if(status.status==='error') throw new Error('PHP preview failed'); await new Promise(resolve=>setTimeout(resolve,100)); } throw new Error('PHP preview did not start'); });
 const html=await (await fetch(runtime.url)).text();
 if(!html.includes('Your next adventure starts here.')) throw new Error('preview is not the imported project');
 await page.waitForTimeout(700);
 await page.screenshot({path:path.join(os.tmpdir(), 'frameui-canvas.png')});
 await page.getByRole('button',{name:'Duplicate to design',exact:true}).first().click();
 await page.waitForTimeout(1000);
 await page.getByTitle('Fit all',{exact:true}).click();
 const design=page.frameLocator('iframe[title="Editable project design"]').last();
 await design.getByRole('heading',{name:'Your next adventure starts here.'}).click();
 await page.waitForTimeout(300);
 await page.locator('textarea').fill('A new journey, designed locally.');
 await page.waitForTimeout(700);
 await page.screenshot({path:path.join(os.tmpdir(), 'frameui-editable.png')});
 await page.getByRole('button',{name:path.basename(root),exact:true}).click();
 await page.getByRole('button',{name:/Purchase flow/}).last().click();
 await page.waitForTimeout(700);
 await page.frameLocator('iframe[title="Editable project design"]').last().getByRole('heading',{name:'A new journey, designed locally.'}).waitFor();
 await page.getByRole('button',{name:path.basename(root),exact:true}).click();
 await page.getByRole('button',{name:/Blank Design/}).click();
 await page.getByRole('textbox',{name:'Design name'}).fill('New concept');
 await page.getByRole('button',{name:'Create design',exact:true}).click();
 await page.waitForTimeout(700);
 await page.evaluate(() => {
   const source = [...document.querySelectorAll('[draggable="true"]')].find(el => el.textContent.includes('Plan a journey'));
   if(!source) throw new Error('project button missing');
   const transfer = new DataTransfer();
   source.dispatchEvent(new DragEvent('dragstart',{bubbles:true,dataTransfer:transfer}));
   const frame = document.querySelector('iframe[title="Editable project design"]');
   if(!frame?.contentDocument) throw new Error('blank design missing');
   frame.contentDocument.dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer:transfer}));
 });
 await page.frameLocator('iframe[title="Editable project design"]').getByRole('button',{name:'Plan a journey'}).waitFor();
 await page.getByRole('checkbox',{name:'Show grid'}).check();
 await page.getByRole('button',{name:'Add responsive versions'}).click();
 await page.waitForTimeout(600);
 const count = await page.locator('iframe[title="Editable project design"]').count();
 if(count !== 3) throw new Error(`expected 3 responsive frames, got ${count}`);
 await page.getByTitle('Fit all',{exact:true}).click();
 await page.screenshot({path:path.join(os.tmpdir(), 'frameui-responsive.png')});

 await page.getByRole('separator',{name:'Resize left panel'}).focus();
 await page.keyboard.press('ArrowRight');
 const panelWidth = await page.getByRole('separator',{name:'Resize left panel'}).getAttribute('aria-valuenow');
 await page.getByTitle('Focus canvas',{exact:true}).click();
 if(await page.getByRole('separator').count()) throw new Error('Focus did not fully hide panels');
 await page.getByRole('button',{name:path.basename(root),exact:true}).click();
 await page.getByRole('button',{name:/New concept/}).last().click();
 await page.getByTitle('Focus canvas',{exact:true}).waitFor();
 if(await page.getByRole('separator').count()) throw new Error('Focus state not restored');
 await page.getByTitle('Toggle pages and layers',{exact:true}).click();
 if(await page.getByRole('separator',{name:'Resize left panel'}).getAttribute('aria-valuenow') !== panelWidth) throw new Error('Panel width not restored');
 await page.getByTitle('Toggle inspector',{exact:true}).click();
 await page.getByRole('button',{name:'Application settings',exact:true}).click();
 await page.getByRole('radio',{name:'Light',exact:true}).check();
 await page.getByRole('button',{name:'Close settings',exact:true}).click();
 await page.screenshot({path:path.join(os.tmpdir(), 'frameui-light-canvas.png')});
 await page.reload();
 await page.getByTitle('Focus canvas',{exact:true}).waitFor({timeout:20000});
 if(await page.evaluate(() => document.documentElement.dataset.theme) !== 'light') throw new Error('Appearance not restored');
 if(await page.getByRole('separator',{name:'Resize left panel'}).getAttribute('aria-valuenow') !== panelWidth) throw new Error('Panel width lost on restart');
 await page.frameLocator('iframe[title="Editable project design"]').first().getByRole('button',{name:'Plan a journey'}).waitFor();
 console.log('PASS: welcome, themes, home, PHP flow, edits, saved text, responsive copies, focus restoration, resized panels, session reload');
 await page.evaluate(() => window.frameui.preview.stop());
 await app.close();
 application = null;
})().catch(async e => { console.error(e); if (application) await application.close(); process.exitCode = 1; });
