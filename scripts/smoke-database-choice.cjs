const { _electron } = require('playwright-core')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const assert = require('node:assert/strict')
;(async () => {
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'frameui-database-choice-'))
 let app
 try {
  const source=path.join(root,'Budget');fs.mkdirSync(source)
  fs.writeFileSync(path.join(source,'composer.json'),JSON.stringify({name:'fixture/budget',require:{php:'^8.4'}}))
  fs.writeFileSync(path.join(source,'index.php'),'<?php echo "Budget";')
  fs.writeFileSync(path.join(source,'.env'),'DB_CONNECTION=mysql\nDB_HOST=127.0.0.1\nDB_DATABASE=budget\n')
  const env={...process.env,FRAMEUI_ALLOW_MULTIPLE_INSTANCES:'1'};delete env.ELECTRON_RUN_AS_NODE
  app=await _electron.launch({executablePath:process.env.FRAMEUI_ELECTRON_PATH||require('electron'),args:[path.resolve(__dirname,'..'),`--user-data-dir=${root}/profile`],env})
  const page=await app.firstWindow();await page.setViewportSize({width:1280,height:900})
  await page.getByRole('button',{name:'Get started',exact:true}).click()
  await app.evaluate(({dialog},folder)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[folder]})},source)
  await page.getByRole('button',{name:'New Design Project',exact:true}).first().click()
  const prepare=page.getByRole('button',{name:'Prepare workspace',exact:true});await prepare.waitFor({timeout:60000})
  await page.locator('dialog[open]').waitFor({state:'hidden'})
  await prepare.click()
  const modal=page.getByRole('dialog',{name:/Choose data for/});await modal.waitFor()
  assert.equal(await modal.getByRole('button',{name:'Continue setup'}).isDisabled(),true)
  await modal.getByRole('radio',{name:/Use an existing local database/}).check()
  assert.equal(await modal.getByRole('button',{name:'Continue setup'}).isEnabled(),true)
  await page.screenshot({path:path.join(__dirname,'../docs/database-choice-smoke.png')})
  await modal.getByRole('button',{name:'Cancel',exact:true}).click()
  await modal.waitFor({state:'hidden'})
  await prepare.click();await modal.waitFor()
  assert.equal(await modal.getByRole('button',{name:'Continue setup'}).isDisabled(),true)
  await page.keyboard.press('Escape');await modal.waitFor({state:'hidden'})
  assert.equal(fs.existsSync(path.join(source,'vendor')),false)
  console.log('Database choice opens before setup, requires selection, resets on reopen, and supports Cancel/Escape without installing dependencies.')
 } finally { if(app)await app.close();fs.rmSync(root,{recursive:true,force:true}) }
})().catch(error=>{console.error(error);process.exitCode=1})
