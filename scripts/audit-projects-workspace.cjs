const { _electron } = require('playwright-core')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), assert = require('node:assert/strict')
;(async () => {
 const root = fs.mkdtempSync(path.join(os.tmpdir(), 'frameui-projects-audit-'))
 const output = path.resolve('docs/projects-workspace-audit'); fs.mkdirSync(output, { recursive:true })
 let app
 try {
  const env = { ...process.env, FRAMEUI_ALLOW_MULTIPLE_INSTANCES:'1' }; delete env.ELECTRON_RUN_AS_NODE
  app = await _electron.launch({ executablePath:process.env.FRAMEUI_ELECTRON_PATH || require('electron'), args:[path.resolve('.'), `--user-data-dir=${root}/profile`], env })
  const page = await app.firstWindow(), errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.setViewportSize({width:1440,height:1000})
  await page.getByRole('button', {name:'Get started',exact:true}).click()
  await page.getByRole('heading', {name:'Start your first FrameUI project'}).waitFor()
  assert.equal(await page.getByRole('heading', {name:'All Projects'}).count(),0)
  for(const theme of ['light','dark']) {
   await page.evaluate(theme => document.documentElement.dataset.theme=theme, theme)
   await page.screenshot({animations:'disabled',path:path.join(output,`${theme}-empty.png`)})
  }
  // Exercise the real folder picker entry without starting preparation.
  await app.evaluate(({dialog}) => { dialog.showOpenDialog=async()=>({canceled:true,filePaths:[]}) })
  await page.getByRole('button',{name:'Choose a project folder',exact:true}).click()
  await page.getByRole('button',{name:'Clone from GitHub',exact:true}).click()
  await page.locator('dialog[open]').waitFor(); await page.keyboard.press('Escape')
  const source = path.join(root,'source'); fs.mkdirSync(source); fs.writeFileSync(path.join(source,'keep.txt'),'source untouched')
  const library = path.join(root,'profile/workspace/project-library.json')
  const history = path.join(root,'profile/workspace/project-recent-history.json')
  const records = Array.from({length:50},(_,i)=>({id:`00000000-0000-4000-8000-${String(i).padStart(12,'0')}`,name:i===0?'Budget App':`Project ${String(i).padStart(2,'0')}`,path:source,addedAt:new Date(Date.now()-i*86400000).toISOString(),lastOpenedAt:new Date(Date.now()-i*60000).toISOString()}))
  function seed(data) { fs.mkdirSync(path.dirname(library),{recursive:true}); fs.writeFileSync(library,JSON.stringify({schemaVersion:1,data})); fs.writeFileSync(history,JSON.stringify({schemaVersion:1,data:data.map(p=>({projectId:p.id,openedAt:p.lastOpenedAt}))})) }
  seed(records.slice(0,1)); await page.reload(); await page.getByRole('heading',{name:'All Projects 1',exact:true}).waitFor()
  assert.equal(await page.locator('.project-tile').count(),1)
  seed(records); await page.reload(); await page.getByRole('heading',{name:'All Projects 50',exact:true}).waitFor()
  assert.equal(await page.locator('.project-tile').count(),6)
  assert.equal(await page.locator('.project-tile strong').first().innerText(),'Budget App')
  assert.equal(await page.locator('.project-row').count(),50)
  for(const theme of ['light','dark']) {
   await page.evaluate(theme => document.documentElement.dataset.theme=theme,theme)
   await page.screenshot({animations:'disabled',path:path.join(output,`${theme}-library.png`)})
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  }
  await page.locator('.projects-content').evaluate(element => element.scrollTop = element.scrollHeight)
  const actionBounds = await page.getByRole('button',{name:'New Design Project',exact:true}).boundingBox()
  assert.ok(actionBounds && actionBounds.y >= 0 && actionBounds.y < 150, 'project action stays visible while scrolling')
  await page.locator('.projects-content').evaluate(element => element.scrollTop = 0)
  await page.getByRole('textbox',{name:'Search projects'}).fill('Budget')
  assert.equal(await page.locator('.project-row').count(),1)
  await page.getByRole('button',{name:'Grid view',exact:true}).click()
  assert.equal(await page.locator('.project-tile').count(),7)
  await page.getByRole('textbox',{name:'Search projects'}).fill('no such project')
  await page.getByRole('button',{name:'Clear search',exact:true}).click()
  await page.getByRole('button',{name:'List view',exact:true}).click()
  await page.getByLabel('Sort projects').selectOption('name')
  await page.locator('.project-row').first().click({button:'right'})
  await page.keyboard.press('ArrowDown')
  assert.equal(await page.evaluate(()=>document.activeElement.textContent), 'Rename')
  await page.keyboard.press('Enter')
  await page.locator('.project-rename input').fill('Renamed Budget')
  await page.getByRole('button',{name:'Save name',exact:true}).click()
  await page.locator('.project-rename').waitFor({state:'detached'})
  assert.equal(JSON.parse(fs.readFileSync(library)).data[0].name,'Renamed Budget')
  await page.reload(); await page.getByRole('textbox',{name:'Search projects'}).fill('Renamed Budget')
  await page.locator('.project-row').first().click({button:'right'})
  await page.getByRole('menuitem',{name:'Remove from FrameUI',exact:true}).click()
  await page.getByRole('heading',{name:'All Projects 49',exact:true}).waitFor()
  assert.equal(fs.readFileSync(path.join(source,'keep.txt'),'utf8'),'source untouched')
  await page.getByRole('button',{name:'Clear search',exact:true}).click()
  await page.setViewportSize({width:800,height:700})
  await page.screenshot({animations:'disabled',path:path.join(output,'compact-library.png')})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  assert.deepEqual(errors,[])
  console.log('Verified empty, one and fifty projects, light/dark, responsive layout, history order, search, grid/list, rename persistence and safe removal.')
 } finally { if(app) await app.close(); fs.rmSync(root,{recursive:true,force:true}) }
})().catch(error=>{console.error(error);process.exitCode=1})
