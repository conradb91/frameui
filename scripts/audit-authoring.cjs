const { _electron: electron } = require('playwright-core');
const fs = require('fs'); const os = require('os'); const path = require('path');
let app, page;
(async () => {
 const root = fs.mkdtempSync(path.join(os.tmpdir(), 'frameui-authoring-'));
 const repo = path.join(root, 'repository'); fs.mkdirSync(repo);
 fs.writeFileSync(path.join(repo, 'index.html'), '<main><h1>Audit application</h1><button>Continue</button></main>');
 app = await electron.launch({executablePath:process.env.FRAMEUI_EXECUTABLE || require('electron'),args:[path.resolve(__dirname,'..'),`--user-data-dir=${root}/profile`],env:{...process.env,ELECTRON_RUN_AS_NODE:'',FRAMEUI_ALLOW_MULTIPLE_INSTANCES:'1'}});
 page = await app.firstWindow(); page.setDefaultTimeout(8000); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 page.on('dialog',d=>d.accept());
 await page.getByRole('button',{name:'Get started',exact:true}).click();
 await app.evaluate(({dialog},repo)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[repo]})},repo);
 await page.getByRole('button',{name:'Open Project',exact:true}).first().click();
 await page.getByRole('heading',{name:'A place for your next idea.'}).waitFor();
 const command=async(name)=>{const input=page.getByPlaceholder(/Quick open/);await input.fill(name);await page.getByRole('button',{name:new RegExp('^'+name)}).click();await input.fill('');await input.press('Escape');};
 await command('Open Features');
 await page.getByRole('button',{name:'New Feature',exact:true}).first().click();
 await page.getByPlaceholder('Feature name',{exact:true}).fill('Audit feature');
 await page.getByRole('button',{name:'Create',exact:true}).click();
 await page.getByRole('button',{name:'Audit feature',exact:true}).click();
 await page.getByRole('button',{name:'Components',exact:true}).click();
 await page.getByRole('button',{name:/^Concept Components/}).click();
 await page.getByRole('button',{name:'New',exact:true}).click();
 await page.getByPlaceholder('e.g. PaymentProgress').fill('AuditProgress');
 await page.getByRole('button',{name:'Create',exact:true}).click();
 await page.getByTitle('Delete',{exact:true}).click();
 await page.getByRole('dialog',{name:'Delete AuditProgress'}).waitFor();
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 await page.getByRole('button',{name:'Back',exact:true}).click();
 await page.getByRole('button',{name:'Edit',exact:true}).click();
 await page.getByTitle('Delete',{exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Delete',exact:true}).click();
 await page.getByText('No concept components yet.',{exact:false}).waitFor();
 console.log('PASS: feature creation, component creation, editor delete confirmation, cancel and confirmed deletion');
 await page.getByRole('button',{name:'Pages',exact:true}).click();
 await page.getByRole('button',{name:'Create New Page',exact:true}).click();
 await page.getByRole('button',{name:/^Blank Page/}).click();
 await page.getByPlaceholder('e.g. Payment Overview').fill('Audit new page');
 await page.getByRole('button',{name:'Create Page',exact:true}).click();
 await page.waitForTimeout(300);
 const created = await page.evaluate(async()=>{const project=(await window.frameui.project.listLibrary())[0];const features=await window.frameui.workspace.listFeatures(project.id);return features.find(f=>f.name==='Audit feature')});
 if(created.newPageIds.length!==1)throw new Error('New page was not persisted in feature');
 await app.evaluate(({dialog},output)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:output})},path.join(root,'audit-export.svg'));
 await page.getByRole('button',{name:'Export',exact:true}).click();
 await page.getByRole('button',{name:'Export first selection',exact:true}).click();
 await page.getByText('Saved '+path.join(root,'audit-export.svg'),{exact:true}).waitFor();
 if(!fs.readFileSync(path.join(root,'audit-export.svg'),'utf8').includes('<svg'))throw new Error('Invalid SVG export');
 console.log('PASS: new page creation, persisted feature membership and SVG export through save dialog');
 if(errors.length) throw new Error(errors.join('\n'));
 await app.close();app=null;
})().catch(async error=>{console.error(error);if(page){console.error((await page.locator('body').innerText()).slice(0,7000));await page.screenshot({path:path.join(os.tmpdir(),'frameui-authoring-failure.png')}).catch(()=>{});}if(app)await app.close();process.exitCode=1;});
